import { describe, expect, it } from 'vitest';
import { editable, insidePackage, mayWrite } from '@/core/packages/writable';
import { catalogue } from '@/shared/i18n/translate';

/**
 * The rules that stand between a browser and a filesystem.
 *
 * `path` comes from the page, so every one of these is an attempt somebody could make.
 * The traversal cases matter most: the panel runs as a user with a home directory, a git
 * identity and an SSH key, and a write that escapes the package folder reaches all three.
 */
describe('whether a path names a file inside the package', () => {
  it('accepts the files a package is made of', () => {
    for (const path of ['acceptance.md', 'roles/api.md', 'decisions.md']) {
      expect(insidePackage(path), path).toBe(true);
    }
  });

  it('refuses a path that climbs out', () => {
    for (const path of ['../secrets.md', 'roles/../../x.md', '..', 'a/../../b.md']) {
      expect(insidePackage(path), path).toBe(false);
    }
  });

  it('refuses an absolute path, on either kind of machine', () => {
    for (const path of ['/etc/passwd', '\\\\server\\share', 'C:/Windows/x.md']) {
      expect(insidePackage(path), path).toBe(false);
    }
  });

  it('refuses a separator it does not understand, and a null byte', () => {
    expect(insidePackage('roles\\core.md')).toBe(false);
    expect(insidePackage('a\0b.md')).toBe(false);
  });

  it('refuses nothing at all, and a path longer than any real one', () => {
    expect(insidePackage('')).toBe(false);
    expect(insidePackage('   ')).toBe(false);
    expect(insidePackage(`${'a'.repeat(300)}.md`)).toBe(false);
  });
});

describe('which files may be written', () => {
  it('lets a researcher write the research', () => {
    expect(mayWrite('acceptance.md', 'researcher', ['researcher'])).toEqual({ ok: true });
  });

  it('refuses a file generated by a tool', () => {
    // Hand-editing these makes the tooling disagree with its own output.
    for (const path of ['task.json', '.validation.md', '.lock.json']) {
      expect(mayWrite(path, 'researcher', ['researcher']), path).toEqual({
        ok: false,
        reasonKey: 'package.write.generated',
      });
    }
  });

  it('refuses the other half of the package', () => {
    expect(mayWrite('plan.md', 'developer', ['researcher'])).toEqual({
      ok: false,
      reasonKey: 'package.write.notYours',
    });
  });

  it('lets somebody who is both write either half', () => {
    expect(mayWrite('plan.md', 'developer', ['researcher', 'developer'])).toEqual({ ok: true });
    expect(mayWrite('research.md', 'researcher', ['researcher', 'developer'])).toEqual({ ok: true });
  });

  it('refuses a traversal before it considers anything else', () => {
    expect(mayWrite('../../.ssh/config', 'researcher', ['researcher'])).toEqual({
      ok: false,
      reasonKey: 'package.write.outside',
    });
  });

  it('refuses a file that is not prose', () => {
    expect(editable('notes.txt')).toBe(false);
    expect(mayWrite('notes.txt', 'researcher', ['researcher'])).toEqual({
      ok: false,
      reasonKey: 'package.write.unreadable',
    });
  });

  it('has a sentence for every refusal in both languages', () => {
    const refusals = [
      mayWrite('../x.md', 'researcher', ['researcher']),
      mayWrite('task.json', 'researcher', ['researcher']),
      mayWrite('plan.md', 'developer', ['researcher']),
      mayWrite('notes.txt', 'researcher', ['researcher']),
    ];
    for (const locale of ['tr', 'en'] as const) {
      const messages = catalogue(locale);
      for (const refusal of refusals) {
        if (refusal.ok) continue;
        expect(messages[refusal.reasonKey], `${locale} ${refusal.reasonKey}`).toBeTruthy();
      }
    }
  });
});
